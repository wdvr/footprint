import Foundation

/// A gazetteer city (production spec §2.3). Field names follow the spec's `City`
/// record so the build-time gazetteer can replace `BundledCityGazetteer` behind
/// `CityGazetteerSource` without touching the city UI or collection counting.
struct GazetteerCity: Codable, Identifiable, Hashable, Sendable {
    /// GeoNames key, "gn:5391959"; also the `regionCode` of a city `VisitedPlace`.
    let id: String
    let name: String
    let countryCode: String
    /// "US-CA"; set for US state capitals.
    let subdivisionCode: String?
    let countyFips: String?
    let lat: Double
    let lon: Double
    let radiusMeters: Double
    let population: Int
    let isNationalCapital: Bool
    let isSubdivisionCapital: Bool
    let timeZone: String?

    var isUSStateCapital: Bool { isSubdivisionCapital && countryCode == "US" }
    var isCapital: Bool { isNationalCapital || isSubdivisionCapital }

    /// Match radius scaled with population, clamped to 1.5–15 km (spec §2.3).
    static func matchRadius(population: Int) -> Double {
        let scaled = 1_500 + 13_500 * (Double(max(population, 0)) / 10_000_000).squareRoot()
        return min(max(scaled, 1_500), 15_000)
    }
}

/// Supplies the city list. Today: the bundled JSON files. Later: the generated gazetteer.
protocol CityGazetteerSource: Sendable {
    func loadCities() throws -> (cities: [GazetteerCity], dataVersion: String)
}

/// Read-only index over a gazetteer source. All city UI and counting read through this.
final class CityGazetteer: Sendable {
    let cities: [GazetteerCity]
    let dataVersion: String
    private let byID: [String: GazetteerCity]

    init(cities: [GazetteerCity], dataVersion: String) {
        self.cities = cities.sorted { ($0.countryCode, $0.name) < ($1.countryCode, $1.name) }
        self.dataVersion = dataVersion
        self.byID = Dictionary(cities.map { ($0.id, $0) }, uniquingKeysWith: { first, _ in first })
    }

    convenience init(source: CityGazetteerSource) throws {
        let loaded = try source.loadCities()
        self.init(cities: loaded.cities, dataVersion: loaded.dataVersion)
    }

    static let shared: CityGazetteer = {
        do {
            return try CityGazetteer(source: BundledCityGazetteer.fromBundle())
        } catch {
            return CityGazetteer(cities: [], dataVersion: "unavailable")
        }
    }()

    func city(id: String) -> GazetteerCity? { byID[id] }

    func cities(in collection: CityCollection) -> [GazetteerCity] {
        cities.filter(collection.contains)
    }

    func cities(inCountry countryCode: String) -> [GazetteerCity] {
        cities.filter { $0.countryCode == countryCode }
    }
}

/// Builds the gazetteer from the bundled `world_cities.json` (cities ≥250k, keyed by
/// GeoNames id) merged with `capitals.json` (195 national + 51 US state capitals),
/// both generated by `scripts/build_city_collections.py`.
struct BundledCityGazetteer: CityGazetteerSource {
    let citiesData: Data
    let capitalsData: Data

    enum LoadError: Error {
        case missingResource(String)
    }

    static func fromBundle(_ bundle: Bundle = .main) throws -> BundledCityGazetteer {
        func data(_ name: String) throws -> Data {
            guard let url = bundle.url(forResource: name, withExtension: "json", subdirectory: "GeoData")
                ?? bundle.url(forResource: name, withExtension: "json")
            else { throw LoadError.missingResource(name) }
            return try Data(contentsOf: url)
        }
        return BundledCityGazetteer(citiesData: try data("world_cities"), capitalsData: try data("capitals"))
    }

    private struct WorldCity: Decodable {
        let id: String?
        let name: String
        let pop: Int
        let lat: String
        let lng: String
    }

    private struct CapitalsFile: Decodable {
        let dataVersion: String
        let cities: [Capital]
    }

    private struct Capital: Decodable {
        let id: String
        let name: String
        let countryCode: String
        let subdivisionCode: String?
        let lat: Double
        let lon: Double
        let population: Int
        let isNationalCapital: Bool
        let isSubdivisionCapital: Bool
        let timeZone: String?
    }

    func loadCities() throws -> (cities: [GazetteerCity], dataVersion: String) {
        let world = try JSONDecoder().decode([String: [WorldCity]].self, from: citiesData)
        let capitals = try JSONDecoder().decode(CapitalsFile.self, from: capitalsData)

        var result: [String: GazetteerCity] = [:]
        for (countryCode, entries) in world {
            for entry in entries {
                guard let lat = Double(entry.lat), let lon = Double(entry.lng) else { continue }
                let id = entry.id ?? Self.fallbackID(countryCode: countryCode, name: entry.name)
                guard result[id] == nil else { continue }
                result[id] = GazetteerCity(
                    id: id,
                    name: entry.name,
                    countryCode: countryCode,
                    subdivisionCode: nil,
                    countyFips: nil,
                    lat: lat,
                    lon: lon,
                    radiusMeters: GazetteerCity.matchRadius(population: entry.pop),
                    population: entry.pop,
                    isNationalCapital: false,
                    isSubdivisionCapital: false,
                    timeZone: nil
                )
            }
        }
        // Capitals carry the flags; where a capital is also a large city, the
        // world_cities row keeps its name and population and gains the flags.
        for capital in capitals.cities {
            let existing = result[capital.id]
            let population = existing?.population ?? capital.population
            result[capital.id] = GazetteerCity(
                id: capital.id,
                name: existing?.name ?? capital.name,
                countryCode: capital.countryCode,
                subdivisionCode: capital.subdivisionCode,
                countyFips: nil,
                lat: existing?.lat ?? capital.lat,
                lon: existing?.lon ?? capital.lon,
                radiusMeters: GazetteerCity.matchRadius(population: population),
                population: population,
                isNationalCapital: capital.isNationalCapital,
                isSubdivisionCapital: capital.isSubdivisionCapital,
                timeZone: capital.timeZone
            )
        }
        return (Array(result.values), capitals.dataVersion)
    }

    /// Stable key for the few bundled cities GeoNames could not match.
    static func fallbackID(countryCode: String, name: String) -> String {
        "wc:\(countryCode):\(name.lowercased().replacingOccurrences(of: " ", with: "-"))"
    }
}
