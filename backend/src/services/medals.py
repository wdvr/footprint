"""Medals v2 evaluation (spec §4.1), a port of the iOS `MedalEngine`.

The catalog is generated by `scripts/build_medals_catalog.py`; iOS and the
backend read byte-identical copies. Facts are replayed in date order, so each
tier's `earned_at` is the date of the place that first crossed its threshold.
The backend evaluates only medals whose catalog `platforms` include
"backend": the ones derivable from synced places.
"""

import json
import math
from dataclasses import dataclass, field
from datetime import UTC, datetime
from functools import lru_cache
from pathlib import Path
from typing import Any

from src.models.geographic import get_country_timezones

CATALOG_PATH = Path(__file__).resolve().parent.parent / "data" / "medals.json"
EPOCH = datetime(1970, 1, 1, tzinfo=UTC)


@lru_cache(maxsize=1)
def load_catalog() -> dict[str, Any]:
    return json.loads(CATALOG_PATH.read_text(encoding="utf-8"))


@dataclass(frozen=True)
class PlaceFact:
    region_type: str
    region_code: str
    name: str
    date: datetime
    time_zones: tuple[int, ...] = ()
    dated: bool = True


@dataclass(frozen=True)
class TierAward:
    level: str
    threshold: float
    earned_at: datetime | None
    trigger: str


@dataclass
class MedalResult:
    definition: dict[str, Any]
    value: float
    awards: list[TierAward] = field(default_factory=list)

    @property
    def highest_award(self) -> TierAward | None:
        return self.awards[-1] if self.awards else None

    @property
    def next_tier(self) -> dict[str, Any] | None:
        reached = self.highest_award.threshold if self.highest_award else -1
        return next(
            (t for t in self.definition["tiers"] if t["threshold"] > reached), None
        )

    @property
    def progress_total(self) -> float:
        tier = self.next_tier or self.definition["tiers"][-1]
        return tier["threshold"]


def _parse_date(value: Any) -> datetime | None:
    if value is None or value == "":
        return None
    if isinstance(value, datetime):
        return value if value.tzinfo else value.replace(tzinfo=UTC)
    text = str(value).replace("Z", "+00:00")
    parsed = datetime.fromisoformat(text)
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=UTC)


def counts_toward_medals(place: dict[str, Any]) -> bool:
    """Visited, full (non-transit) and not deleted, as on iOS."""
    return (
        not place.get("is_deleted", False)
        and place.get("status", "visited") == "visited"
        and place.get("visit_type", "visited") == "visited"
    )


def place_facts(places: list[dict[str, Any]]) -> list[PlaceFact]:
    facts = []
    for place in places:
        if not counts_toward_medals(place):
            continue
        # Simple sync stores no visit or mark date; created_at is when the server first saw it.
        date = (
            _parse_date(place.get("visited_date"))
            or _parse_date(place.get("marked_at"))
            or _parse_date(place.get("created_at"))
        )
        region_type = place.get("region_type", "")
        code = place.get("region_code", "")
        zones = tuple(get_country_timezones(code)) if region_type == "country" else ()
        facts.append(
            PlaceFact(
                region_type=region_type,
                region_code=code,
                name=place.get("region_name") or code,
                date=date or EPOCH,
                time_zones=zones,
                dated=date is not None,
            )
        )
    return facts


def month_index(date: datetime) -> int:
    d = date.astimezone(UTC)
    return d.year * 12 + d.month


def week_index(date: datetime) -> int:
    days = math.floor(date.timestamp() / 86_400)
    return math.floor((days + 3) / 7)


def whole_years(start: datetime, end: datetime) -> int:
    a, b = start.astimezone(UTC), end.astimezone(UTC)
    before = (b.month, b.day) < (a.month, a.day)
    return max(0, b.year - a.year - (1 if before else 0))


class _Streak:
    def __init__(self) -> None:
        self.best = 0
        self._current = 0
        self._last: int | None = None

    def add(self, index: int) -> None:
        if self._last is not None and index == self._last:
            return
        consecutive = self._last is not None and index == self._last + 1
        self._current = self._current + 1 if consecutive else 1
        self._last = index
        self.best = max(self.best, self._current)


class _State:
    def __init__(self, catalog: dict[str, Any]) -> None:
        self.catalog = catalog
        self.subdivision_country = catalog["subdivisionRegionTypes"]
        self.countries: set[str] = set()
        self.subdivisions: dict[str, set[str]] = {}
        self.counties: set[str] = set()
        self.regions: set[str] = set()
        self.zones: set[int] = set()
        self.months = _Streak()
        self.weeks = _Streak()
        self.years: set[int] = set()
        self.first: datetime | None = None
        self.last: datetime | None = None

    def apply(self, fact: PlaceFact) -> None:
        if fact.region_type == "country":
            self.countries.add(fact.region_code)
        elif fact.region_type in self.subdivision_country:
            country = self.subdivision_country[fact.region_type]
            self.subdivisions.setdefault(country, set()).add(fact.region_code)
        elif fact.region_type == self.catalog["countyRegionType"]:
            self.counties.add(fact.region_code)
        elif fact.region_type == self.catalog["namedRegionRegionType"]:
            self.regions.add(fact.region_code)
        self.zones.update(fact.time_zones)
        if not fact.dated:
            return
        self.months.add(month_index(fact.date))
        self.weeks.add(week_index(fact.date))
        self.years.add(fact.date.astimezone(UTC).year)
        self.first = min(self.first or fact.date, fact.date)
        self.last = max(self.last or fact.date, fact.date)

    def _continent_counts(self) -> dict[str, int]:
        counts: dict[str, int] = {}
        for code in self.countries:
            continent = self.catalog["countryContinents"].get(code)
            if continent:
                counts[continent] = counts.get(continent, 0) + 1
        return counts

    def value(self, medal: dict[str, Any]) -> float:  # noqa: C901
        f = medal.get("filter") or {}
        metric = medal["metric"]
        if metric == "countriesVisited":
            return len(self.countries)
        if metric == "subdivisionsVisited":
            if "country" in f:
                return len(self.subdivisions.get(f["country"], ()))
            return sum(len(s) for s in self.subdivisions.values())
        if metric == "subdivisionSet":
            visited = self.subdivisions.get(f.get("country", ""), set())
            return sum(1 for m in medal.get("members", []) if m in visited)
        if metric == "homeCountryCompletion":
            candidates = [(c, s) for c, s in self.subdivisions.items() if s]
            if not candidates:
                return 0
            home, visited = sorted(candidates, key=lambda cs: (-len(cs[1]), cs[0]))[0]
            total = self.catalog["subdivisionCounts"].get(home, 0)
            return math.floor(len(visited) / total * 100) if total else 0
        if metric == "countiesVisited":
            return len(self.counties)
        if metric == "countiesInState":
            state = self.catalog["countyStates"].get(f.get("state", ""))
            if not state:
                return 0
            return sum(1 for c in self.counties if c.startswith(state["fips"]))
        if metric == "regionsVisited":
            return len(self.regions)
        if metric == "continentCountries":
            counts = self._continent_counts()
            wanted = [c for c in f.get("continents", "").split(",") if c]
            return sum(counts.get(c, 0) for c in wanted)
        if metric == "continentsTouched":
            return len(self._continent_counts())
        if metric == "countriesInSet":
            members = set(self.catalog["countrySets"].get(f.get("set", ""), []))
            return len(self.countries & members)
        if metric == "timeZonesVisited":
            return len(self.zones)
        if metric == "dateLineCrossed":
            east = any(z >= int(f.get("east", 12)) for z in self.zones)
            west = any(z <= int(f.get("west", -10)) for z in self.zones)
            return 1 if east and west else 0
        if metric == "newPlaceStreakMonths":
            return self.months.best
        if metric == "newPlaceStreakWeeks":
            return self.weeks.best
        if metric == "distinctYearsActive":
            return len(self.years)
        if metric == "yearsSpan":
            if self.first is None or self.last is None:
                return 0
            return whole_years(self.first, self.last)
        return 0


def _events(facts: list[PlaceFact]) -> list[PlaceFact]:
    first: dict[tuple[str, str], PlaceFact] = {}
    for fact in facts:
        key = (fact.region_type, fact.region_code)
        if key in first and first[key].date <= fact.date:
            continue
        first[key] = fact
    return sorted(
        first.values(),
        key=lambda f: (f.date, f"0|{f.region_type}|{f.region_code}"),
    )


def evaluate(
    places: list[dict[str, Any]],
    catalog: dict[str, Any] | None = None,
    platform: str = "backend",
) -> list[MedalResult]:
    """Evaluate every catalog medal for `platform` over a user's synced places."""
    catalog = catalog or load_catalog()
    medals = [m for m in catalog["medals"] if platform in m["platforms"]]
    state = _State(catalog)
    awards: dict[str, list[TierAward]] = {m["id"]: [] for m in medals}
    for fact in _events(place_facts(places)):
        state.apply(fact)
        for medal in medals:
            have = awards[medal["id"]]
            if len(have) == len(medal["tiers"]):
                continue
            value = state.value(medal)
            for tier in medal["tiers"][len(have) :]:
                if value >= tier["threshold"]:
                    have.append(
                        TierAward(
                            level=tier["level"],
                            threshold=tier["threshold"],
                            earned_at=fact.date if fact.dated else None,
                            trigger=fact.name,
                        )
                    )
    return [
        MedalResult(definition=m, value=state.value(m), awards=awards[m["id"]])
        for m in medals
    ]
